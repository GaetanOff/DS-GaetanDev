export type IconName = keyof typeof PATHS

/**
 * Render an icon.
 *
 * @param name  key from the set — unknown names render nothing
 * @param cls   Tailwind classes, always include a size (`w-5 h-5`)
 * @param width stroke width; 1.5 reads better at 48px+, 2 is the default
 */
export function icon(name: IconName | string, cls = 'w-5 h-5', width: 1.5 | 2 = 2): string {
  const d = PATHS[name as IconName]
  if (!d) return ''
  const paths = (Array.isArray(d) ? d : [d])
    .map(p => `<path stroke-linecap="round" stroke-linejoin="round" stroke-width="${width}" d="${p}"/>`)
    .join('')
  return `<svg class="${cls}" fill="none" stroke="currentColor" viewBox="0 0 24 24" aria-hidden="true">${paths}</svg>`
}

